function parse(...sources) {
  const glyphs = new Map();
  for (const source of sources) {
    for (const block of source.trim().split(/\n[ \t]*\n/)) {
      const [name, ...rows] = block.split('\n');
      glyphs.set(name, rows);
    }
  }
  return glyphs;
}

export const fonts = {
  wide: parse(SHARED, WIDE),
  narrow: parse(SHARED, NARROW),
};
